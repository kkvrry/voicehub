_EMOTION_SET = frozenset(EMOTIONS)


def canonical_emotion(value: str) -> str:
    """任意情绪说法 → 规范词；认不出返回空串（不是报错，也不是猜一个）。"""
    text = (value or "").strip()
    if not text:
        return ""
    if text in _EMOTION_SET:
        return text
    return EMOTION_SYNONYMS.get(text, "")


def emotion_terms(value: str) -> tuple[str, ...]:
    """一条样例的情绪串 → 词元组：按 :data:`EMOTION_SEP` 拆，去空、去重、保序。

    单值（老数据、扫描推导出来的值）原样返回一项，不需要调用方分两种情况。
    """
    words: list[str] = []
    for part in str(value or "").split(EMOTION_SEP):
        word = part.strip()
        if word and word not in words:
            words.append(word)
    return tuple(words)


def emotion_matches(value: str, target: str) -> bool:
    """样例的情绪里有没有这一种。

    :param value: 样例上存的那串（可能是「严肃、轻蔑」）。
    :param target: **已经归一过**的目标情绪（调用方通常先过 :func:`canonical_emotion`）。

    命中任意一种即算命中：给它标两种，正是因为这两种念法都适用，而不是"只认第一个"。
    认不出的词按原字面比一次——用户自填的词进不了词表，但它照样可能正是要找的那个。
    """
    wanted = (target or "").strip()
    if not wanted:
        return False
    return any((canonical_emotion(word) or word) == wanted for word in emotion_terms(value))
